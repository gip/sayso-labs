import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const swiftPackagePath = path.join(repoRoot, "apps/personal/apple");
const requiredMetadataKeys = ["engine", "engineVersion", "format", "formatVersion", "evalType", "mediaType"];

const fail = (message) => {
  throw new Error(message);
};

const usage = () => {
  fail(
    "Usage: node scripts/runtime-bytecode.mjs <write|check> --package <apps/cli|examples/pong> [--bytecode PATH] [--metadata PATH]",
  );
};

const parseArgs = (argv) => {
  const [mode, ...rest] = argv;
  if (mode !== "write" && mode !== "check") usage();
  const packageFlagIndex = rest.indexOf("--package");
  const packageRelativePath = packageFlagIndex >= 0 ? rest[packageFlagIndex + 1] : undefined;
  if (!packageRelativePath) usage();
  const option = (name) => {
    const index = rest.indexOf(name);
    return index >= 0 ? rest[index + 1] : undefined;
  };
  return {
    mode,
    packageRelativePath,
    bytecodePath: option("--bytecode"),
    metadataPath: option("--metadata"),
  };
};

const parseMetadata = (output) => {
  const values = new Map();
  for (const line of output.split(/\r?\n/)) {
    const match = /^([A-Za-z][A-Za-z0-9]*)=(.*)$/.exec(line.trim());
    if (match) values.set(match[1], match[2]);
  }
  for (const key of requiredMetadataKeys) {
    if (!values.has(key)) fail(`QuickJS bytecode generator did not print ${key}.`);
  }
  return Object.fromEntries(requiredMetadataKeys.map((key) => [key, values.get(key)]));
};

const renderMetadataModule = (metadata) => `// Generated by scripts/runtime-bytecode.mjs. Do not edit by hand.
export const PONG_RUNTIME_BYTECODE_METADATA = {
  engine: ${JSON.stringify(metadata.engine)},
  engineVersion: ${JSON.stringify(metadata.engineVersion)},
  format: ${JSON.stringify(metadata.format)},
  formatVersion: ${JSON.stringify(metadata.formatVersion)},
  evalType: ${JSON.stringify(metadata.evalType)},
  mediaType: ${JSON.stringify(metadata.mediaType)},
} as const;
`;

const ensureSwiftAvailable = () => {
  try {
    execFileSync("swift", ["--version"], {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
  } catch (error) {
    if (error?.code === "ENOENT") {
      fail(
        "Swift toolchain is required to verify or regenerate QuickJS bytecode. Install Swift/Xcode, or run a build command that does not perform bytecode validation.",
      );
    }
    throw error;
  }
};

const compileBytecode = (sourcePath, outputPath) => {
  ensureSwiftAvailable();
  const output = execFileSync(
    "swift",
    ["run", "--package-path", swiftPackagePath, "sayso-qjs-bytecode", sourcePath, outputPath],
    {
      cwd: repoRoot,
      env: {
        ...process.env,
        CLANG_MODULE_CACHE_PATH: process.env.CLANG_MODULE_CACHE_PATH ?? "/tmp/sayso-clang-cache",
        SWIFTPM_HOME: process.env.SWIFTPM_HOME ?? "/tmp/sayso-swiftpm-cache",
      },
      encoding: "utf8",
      stdio: ["ignore", "pipe", "inherit"],
    },
  );
  return parseMetadata(output);
};

const resolveOptionalPath = (value) => (value ? path.resolve(process.cwd(), value) : undefined);

const pathsForPackage = (packageRelativePath, overrides = {}) => {
  if (packageRelativePath !== "apps/cli" && packageRelativePath !== "examples/pong") {
    fail(`Unsupported package path: ${packageRelativePath}`);
  }
  const packageRoot = path.join(repoRoot, packageRelativePath);
  return {
    packageRoot,
    sourcePath: path.join(packageRoot, "src/pong/runtime-app.js"),
    bytecodePath: resolveOptionalPath(overrides.bytecodePath) ?? path.join(packageRoot, "src/pong/runtime-app.qjsc"),
    metadataPath: resolveOptionalPath(overrides.metadataPath) ?? path.join(packageRoot, "src/pong/runtimeBytecode.ts"),
  };
};

const writeArtifacts = ({ sourcePath, bytecodePath, metadataPath }) => {
  mkdirSync(path.dirname(bytecodePath), { recursive: true });
  const metadata = compileBytecode(sourcePath, bytecodePath);
  writeFileSync(metadataPath, renderMetadataModule(metadata));
};

const checkArtifacts = ({ sourcePath, bytecodePath, metadataPath }) => {
  const tempDir = mkdtempSync(path.join(tmpdir(), "sayso-qjs-bytecode-"));
  try {
    const generatedBytecodePath = path.join(tempDir, "runtime-app.qjsc");
    const metadata = compileBytecode(sourcePath, generatedBytecodePath);

    const committedBytecode = readFileSync(bytecodePath);
    const generatedBytecode = readFileSync(generatedBytecodePath);
    if (!committedBytecode.equals(generatedBytecode)) {
      fail(`${path.relative(repoRoot, bytecodePath)} is stale. Run runtime:bytecode:write.`);
    }

    const expectedMetadata = renderMetadataModule(metadata);
    const committedMetadata = readFileSync(metadataPath, "utf8");
    if (committedMetadata !== expectedMetadata) {
      fail(`${path.relative(repoRoot, metadataPath)} is stale. Run runtime:bytecode:write.`);
    }
  } finally {
    rmSync(tempDir, { force: true, recursive: true });
  }
};

try {
  const { mode, packageRelativePath, bytecodePath, metadataPath } = parseArgs(process.argv.slice(2));
  const paths = pathsForPackage(packageRelativePath, { bytecodePath, metadataPath });
  if (mode === "write") {
    writeArtifacts(paths);
  } else {
    checkArtifacts(paths);
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
